import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Turns the html templates into a javascript module the netlify function can bundle.
 *
 * A function is one esbuild bundle; it has no site/templates next to it at run time,
 * and `included_files` would put the markup on a path the bundle cannot name. So the
 * markup is embedded, exactly as the php app embeds it in its views. Nothing in here
 * redesigns a byte of it: the templates are what the untouched php renders, captured
 * and given placeholders only where a value is dynamic.
 *
 * Run through `npm run build`, and committed so a clone needs no build to deploy.
 * `parity/test-views.mjs` is what proves the captured markup still matches the php.
 */

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const tplDir = path.join(root, 'site', 'templates');
const assets = path.join(root, 'site', 'assets');
const outFile = path.join(root, 'site', 'src', 'views', 'pages.gen.mjs');

const NAMES = ['home.html', 'home-chip.html', 'home-row.html', 'error.html', 'error-fatal.html', 'robots.txt'];

/** Documents a visitor receives whole, newlines and all. */
const PAGE_TEMPLATES = new Set(['home.html', 'error.html', 'robots.txt']);

function toId(name) {
  return name.replace(/\.(html|txt)$/, '').replace(/-(\w)/g, (_, c) => c.toUpperCase()) + 'Tpl';
}

/**
 * The php app stamped ASSET_VER from the newest mtime of its own css and js. A netlify
 * deploy has no mtime worth trusting and no file to stat from inside a function, so the
 * stamp is a hash of the shipped files instead, taken at build time and read as a
 * constant by both the static page and the route that answers /index.php.
 */
function assetVersion() {
  // The worker is in this list because the page asks for it under the same version
  // stamp, and an edge that keeps a day-old copy of it would keep a day-old engine.
  const names = ['css/app.css', 'css/material.css', 'js/app.js', 'js/mux-worker.js'];
  const seen = [];
  for (const n of names) {
    const f = path.join(assets, ...n.split('/'));
    if (fs.existsSync(f)) {
      seen.push(crypto.createHash('sha1').update(fs.readFileSync(f)).digest('hex').slice(0, 8));
    }
  }
  return seen.length ? crypto.createHash('sha1').update(seen.join('')).digest('hex').slice(0, 12) : 'dev';
}

const chunks = [
  '// GENERATED BY scripts/generate-views.mjs -- do not edit, edit site/templates instead.',
  '//',
  '// The page is the owner\'s own design, cut to the one tool band the site needs. The',
  '// placeholders are only where a value comes from config or from the registry, and',
  '// parity/test-views.mjs compares those substitutions with php rather than the whole',
  '// document.',
  '',
];

for (const name of NAMES) {
  const file = path.join(tplDir, name);
  if (!fs.existsSync(file)) {
    throw new Error('missing template ' + file);
  }
  // A whole page keeps its final newline, because that is a byte the visitor gets;
  // a fragment's trailing newline is only the editor's hygiene.
  const keepNewline = PAGE_TEMPLATES.has(name);
  const text = keepNewline ? fs.readFileSync(file, 'utf8') : fs.readFileSync(file, 'utf8').replace(/\n$/, '');
  chunks.push('export const ' + toId(name) + ' = ' + JSON.stringify(text) + ';');
}

chunks.push('export const ASSET_VER = ' + JSON.stringify(assetVersion()) + ';');

fs.writeFileSync(outFile, chunks.join('\n') + '\n');
console.log('generate-views: ' + NAMES.length + ' templates and asset version ' + assetVersion()
  + ' embedded into ' + path.relative(root, outFile));
